from __future__ import annotations

import numpy as np
import pytest

from spieceasi.pipeline import spiec_easi_mb
from tests.synthetic_data import generate_strong_signal_counts


def _edge_set(A: np.ndarray) -> set[tuple[int, int]]:
    idx = np.triu_indices(A.shape[0], k=1)
    return {(int(i), int(j)) for i, j in zip(*idx, strict=True) if A[i, j] != 0}


def _precision_recall_f1(
    truth: set[tuple[int, int]],
    pred: set[tuple[int, int]],
) -> tuple[float, float, float, float]:
    tp = len(truth.intersection(pred))
    fp = len(pred.difference(truth))
    fn = len(truth.difference(pred))

    precision = tp / (tp + fp) if (tp + fp) else 0.0
    recall = tp / (tp + fn) if (tp + fn) else 0.0
    f1 = 2 * precision * recall / (precision + recall) if (precision + recall) else 0.0
    jaccard = tp / len(truth.union(pred)) if truth.union(pred) else 1.0
    return precision, recall, f1, jaccard


def _instability_table(alpha_path: np.ndarray, instability: np.ndarray) -> str:
    rows = ["alpha,instability"]
    for a, s in zip(alpha_path, instability, strict=True):
        rows.append(f"{a:.6g},{s:.6f}")
    return "\n".join(rows)


def _count_edges(A: np.ndarray) -> int:
    return int(np.sum(np.triu(A, k=1) != 0))


def _degree_vector(A: np.ndarray) -> np.ndarray:
    return np.sum((A != 0).astype(int), axis=1).astype(float)


def _rank_correlation(x: np.ndarray, y: np.ndarray) -> float:
    if x.size < 2:
        return np.nan
    rank_x = np.argsort(np.argsort(x))
    rank_y = np.argsort(np.argsort(y))
    return float(np.corrcoef(rank_x, rank_y)[0, 1])


def _run_r_spieceasi_mb(
    r_runtime,
    counts_df,
    *,
    nlambda: int,
    lambda_min_ratio: float,
    n_subsamples: int,
    threshold: float,
    seed: int,
) -> tuple[np.ndarray, np.ndarray, float, np.ndarray, np.ndarray, int, float]:
    robjects = r_runtime["robjects"]
    pandas2ri = r_runtime["pandas2ri"]
    localconverter = r_runtime["localconverter"]

    # Convention from SpiecEasi::spiec.easi.default:
    # method='mb', sel.criterion='stars', lambda path generated by getLamPath,
    # default threshold via pulsar params.
    r_code = """
    suppressMessages(library(SpiecEasi))

        run_spieceasi_mb <- function(
            count_df, nlambda, lambda_min_ratio, rep_num, threshold, seed
        ) {
      set.seed(seed)
      X <- as.matrix(count_df)
      fit <- spiec.easi(
        X,
        method = "mb",
        sel.criterion = "stars",
        nlambda = nlambda,
        lambda.min.ratio = lambda_min_ratio,
        pulsar.params = list(rep.num = rep_num, thresh = threshold, seed = seed)
      )

    adj <- as.matrix(getRefit(fit))
    beta_opt <- as.matrix(getOptBeta(fit))
    weight_sym <- as.matrix(symBeta(beta_opt, mode = "ave"))
    weight_sym <- weight_sym * adj
      lambda_path <- as.numeric(fit$lambda)
      opt_lambda <- as.numeric(getOptLambda(fit))
            stars_summary <- as.numeric(fit$select$stars$summary)
            stars_opt <- as.integer(fit$select$stars$opt.index)
            stars_thresh <- as.numeric(fit$select$stars$thresh)
            list(
                adjacency = adj,
                weights = weight_sym,
                selected_lambda = opt_lambda,
                lambda_path = lambda_path,
                stars_summary = stars_summary,
                stars_opt = stars_opt,
                stars_thresh = stars_thresh
            )
    }
    """
    robjects.r(r_code)
    run_fn = robjects.globalenv["run_spieceasi_mb"]

    with localconverter(robjects.default_converter + pandas2ri.converter):
        r_counts_df = robjects.conversion.py2rpy(counts_df)

    r_result = run_fn(
        r_counts_df,
        nlambda,
        lambda_min_ratio,
        n_subsamples,
        threshold,
        seed,
    )
    r_adj = np.asarray(r_result.rx2("adjacency"), dtype=int)
    r_weights = np.asarray(r_result.rx2("weights"), dtype=float)
    r_lambda = float(np.asarray(r_result.rx2("selected_lambda"))[0])
    r_lambda_path = np.asarray(r_result.rx2("lambda_path"), dtype=float)
    r_stars = np.asarray(r_result.rx2("stars_summary"), dtype=float)
    r_opt_index_1b = int(np.asarray(r_result.rx2("stars_opt"), dtype=int)[0])
    r_thresh = float(np.asarray(r_result.rx2("stars_thresh"), dtype=float)[0])
    return (
        r_adj,
        r_weights,
        r_lambda,
        r_lambda_path,
        r_stars,
        r_opt_index_1b,
        r_thresh,
    )


@pytest.mark.r_validation
def test_validate_against_r_spieceasi_mb_deterministic(r_runtime) -> None:
    counts_df, truth_adj = generate_strong_signal_counts(
        n_samples=220,
        n_taxa=24,
        depth=6000,
        rho=0.45,
        seed=31,
    )

    nlambda = 20
    n_subsamples = 20
    threshold = 0.05
    lambda_min_ratio = 1e-2
    seed = 17

    py_result = spiec_easi_mb(
        counts_df,
        n_lambdas=nlambda,
        lambda_min_ratio=lambda_min_ratio,
        n_subsamples=n_subsamples,
        subsample_fraction=0.8,
        stars_threshold=threshold,
        sym_rule="or",
        random_state=seed,
        n_jobs=1,
    )

    r_adj, r_weights, r_lambda, r_lambda_path, r_stars, r_opt_index_1b, r_thresh = (
        _run_r_spieceasi_mb(
            r_runtime,
            counts_df,
            nlambda=nlambda,
            lambda_min_ratio=lambda_min_ratio,
            n_subsamples=n_subsamples,
            threshold=threshold,
            seed=seed,
        )
    )

    r_edge_count = _count_edges(r_adj)
    if r_edge_count == 0:
        pytest.fail(
            "R returned an empty network on strong-signal dataset; "
            "end-to-end parity comparison is not meaningful. "
            f"r_opt_index_1b={r_opt_index_1b}, "
            f"r_lambda_first={r_lambda_path[0]:.6g}, r_lambda_selected={r_lambda:.6g}, "
            f"r_stars_first={r_stars[0]:.6f}, r_threshold={r_thresh:.6f}"
        )

    if r_opt_index_1b in (1, len(r_lambda_path)):
        pytest.fail(
            "R optimal lambda is on path boundary on strong-signal dataset; "
            "diagnostics indicate lambda grid may be poorly calibrated. "
            f"r_opt_index_1b={r_opt_index_1b}, nlambda={len(r_lambda_path)}"
        )

    r_edges = _edge_set(r_adj)
    py_edges = _edge_set(py_result.adjacency)
    precision, recall, f1, jaccard = _precision_recall_f1(r_edges, py_edges)
    node_count_match = int(py_result.adjacency.shape[0] == r_adj.shape[0])
    py_degree = _degree_vector(py_result.adjacency)
    r_degree = _degree_vector(r_adj)
    degree_spearman = _rank_correlation(py_degree, r_degree)
    degree_mae = float(np.mean(np.abs(py_degree - r_degree)))

    truth_edges = _edge_set(truth_adj)
    py_p, py_r, py_f1, _ = _precision_recall_f1(truth_edges, py_edges)
    r_p, r_r, r_f1, _ = _precision_recall_f1(truth_edges, r_edges)

    r_idx = int(np.argmin(np.abs(r_lambda_path - r_lambda)))
    py_idx = int(np.argmin(np.abs(py_result.alpha_path - py_result.selected_lambda)))
    idx_gap = abs(r_idx - py_idx)

    both = np.logical_and(r_adj != 0, py_result.adjacency != 0)
    upper = np.triu_indices_from(both, k=1)
    mask = both[upper]
    shared_edges = int(np.sum(mask))
    if np.any(mask):
        r_w = r_weights[upper][mask]
        py_w = py_result.weights[upper][mask]
        corr = float(np.corrcoef(r_w, py_w)[0, 1]) if shared_edges >= 2 else np.nan
        spearman = _rank_correlation(r_w, py_w)
        mae = float(np.mean(np.abs(r_w - py_w)))
        sign_agree = float(np.mean(np.sign(r_w) == np.sign(py_w)))
    else:
        corr = np.nan
        spearman = np.nan
        mae = np.nan
        sign_agree = np.nan

    diagnostics = (
        f"precision={precision:.3f}, recall={recall:.3f}, f1={f1:.3f}, "
        f"jaccard={jaccard:.3f}, r_lambda={r_lambda:.6g}, "
        f"py_lambda={py_result.selected_lambda:.6g}, idx_gap={idx_gap}, "
        f"node_count_match={node_count_match}, degree_spearman={degree_spearman:.3f}, "
        f"degree_mae={degree_mae:.3f}, "
        f"shared_edges={shared_edges}, weight_corr={corr:.3f}, "
        f"weight_spearman={spearman:.3f}, weight_mae={mae:.3f}, "
        f"weight_sign_agreement={sign_agree:.3f}, py_edges={len(py_edges)}, "
        f"r_edges={len(r_edges)}, "
        f"py_vs_truth_f1={py_f1:.3f}, r_vs_truth_f1={r_f1:.3f}"
    )

    assert node_count_match == 1, diagnostics
    assert precision >= 0.80, diagnostics
    assert recall >= 0.95, diagnostics
    assert f1 >= 0.85, diagnostics
    assert jaccard >= 0.75, diagnostics
    assert degree_mae <= 0.50, diagnostics
    assert py_f1 >= 0.35, diagnostics
    assert r_f1 >= 0.35, diagnostics
    assert shared_edges >= 15, diagnostics
    assert corr >= 0.95, diagnostics
    assert spearman >= 0.90, diagnostics
    assert mae <= 0.10, diagnostics
    assert sign_agree >= 0.95, diagnostics


@pytest.mark.r_validation
def test_validate_against_r_spieceasi_mb_multi_dataset_statistics(r_runtime) -> None:
    configs = [
        (220, 24, 31),
        (240, 24, 41),
        (260, 28, 17),
        (300, 28, 23),
    ]
    nlambda = 20
    n_subsamples = 20
    threshold = 0.05
    lambda_min_ratio = 1e-2

    rows: list[
        tuple[
            int,
            int,
            int,
            float,
            float,
            float,
            float,
            float,
            float,
            float,
            float,
            float,
            float,
            float,
            float,
        ]
    ] = []
    for n_samples, n_taxa, seed in configs:
        counts_df, truth_adj = generate_strong_signal_counts(
            n_samples=n_samples,
            n_taxa=n_taxa,
            depth=6000,
            rho=0.45,
            seed=seed,
        )

        py_result = spiec_easi_mb(
            counts_df,
            n_lambdas=nlambda,
            lambda_min_ratio=lambda_min_ratio,
            n_subsamples=n_subsamples,
            subsample_fraction=0.8,
            stars_threshold=threshold,
            sym_rule="or",
            random_state=seed,
            n_jobs=1,
        )
        r_adj, r_weights, _, r_lambda_path, r_stars, r_opt_index_1b, r_thresh = (
            _run_r_spieceasi_mb(
                r_runtime,
                counts_df,
                nlambda=nlambda,
                lambda_min_ratio=lambda_min_ratio,
                n_subsamples=n_subsamples,
                threshold=threshold,
                seed=seed,
            )
        )

        r_edge_count = _count_edges(r_adj)
        if r_edge_count == 0:
            pytest.fail(
                "R returned an empty network on strong-signal dataset in benchmark. "
                f"n={n_samples}, p={n_taxa}, seed={seed}, "
                f"r_opt_index_1b={r_opt_index_1b}, "
                f"r_lambda_first={r_lambda_path[0]:.6g}, "
                f"r_stars_first={r_stars[0]:.6f}, r_threshold={r_thresh:.6f}"
            )

        truth_edges = _edge_set(truth_adj)
        r_edges = _edge_set(r_adj)
        py_edges = _edge_set(py_result.adjacency)
        precision, recall, f1, jaccard = _precision_recall_f1(r_edges, py_edges)
        node_count_match = float(py_result.adjacency.shape[0] == r_adj.shape[0])
        py_degree = _degree_vector(py_result.adjacency)
        r_degree = _degree_vector(r_adj)
        degree_spearman = _rank_correlation(py_degree, r_degree)
        degree_mae = float(np.mean(np.abs(py_degree - r_degree)))
        _, _, py_f1, _ = _precision_recall_f1(truth_edges, py_edges)
        _, _, r_f1, _ = _precision_recall_f1(truth_edges, r_edges)

        both = np.logical_and(r_adj != 0, py_result.adjacency != 0)
        upper = np.triu_indices_from(both, k=1)
        mask = both[upper]
        shared_edges = int(np.sum(mask))
        if shared_edges >= 2:
            r_w = r_weights[upper][mask]
            py_w = py_result.weights[upper][mask]
            weight_corr = float(np.corrcoef(r_w, py_w)[0, 1])
            weight_spearman = _rank_correlation(r_w, py_w)
            weight_mae = float(np.mean(np.abs(r_w - py_w)))
            weight_sign_agree = float(np.mean(np.sign(r_w) == np.sign(py_w)))
        else:
            weight_corr = np.nan
            weight_spearman = np.nan
            weight_mae = np.nan
            weight_sign_agree = np.nan

        rows.append(
            (
                n_samples,
                n_taxa,
                seed,
                precision,
                recall,
                f1,
                jaccard,
                node_count_match,
                degree_spearman,
                degree_mae,
                py_f1,
                r_f1,
                weight_corr,
                weight_spearman,
                weight_mae,
                weight_sign_agree,
            )
        )

    f1_values = np.asarray([row[5] for row in rows], dtype=float)
    jaccard_values = np.asarray([row[6] for row in rows], dtype=float)
    recall_values = np.asarray([row[4] for row in rows], dtype=float)

    summary = "\n".join(
        (
            "n_samples,n_taxa,seed,precision,recall,f1,jaccard,node_count_match,degree_spearman,degree_mae,py_f1_truth,r_f1_truth,weight_corr,weight_spearman,weight_mae,weight_sign_agree",
            *[
                f"{ns},{nt},{sd},{pr:.3f},{rc:.3f},{f1:.3f},{ja:.3f},{ncm:.0f},{ds:.3f},{dm:.3f},{pyf:.3f},{rf:.3f},{wc:.3f},{ws:.3f},{wm:.3f},{wsa:.3f}"
                for (
                    ns,
                    nt,
                    sd,
                    pr,
                    rc,
                    f1,
                    ja,
                    ncm,
                    ds,
                    dm,
                    pyf,
                    rf,
                    wc,
                    ws,
                    wm,
                    wsa,
                ) in rows
            ],
        )
    )

    node_count_match_values = np.asarray([row[7] for row in rows], dtype=float)
    degree_mae_values = np.asarray([row[9] for row in rows], dtype=float)
    py_f1_truth = np.asarray([row[10] for row in rows], dtype=float)
    r_f1_truth = np.asarray([row[11] for row in rows], dtype=float)
    weight_corr_values = np.asarray([row[12] for row in rows], dtype=float)
    weight_spearman_values = np.asarray([row[13] for row in rows], dtype=float)
    weight_mae_values = np.asarray([row[14] for row in rows], dtype=float)
    weight_sign_agree_values = np.asarray([row[15] for row in rows], dtype=float)

    assert np.median(f1_values) >= 0.90, summary
    assert np.mean(jaccard_values) >= 0.85, summary
    assert np.mean(recall_values) >= 0.95, summary
    assert int(np.sum(f1_values >= 0.85)) >= 4, summary
    assert np.all(node_count_match_values == 1.0), summary
    assert np.max(degree_mae_values) <= 0.50, summary
    assert np.median(py_f1_truth) >= 0.35, summary
    assert np.median(r_f1_truth) >= 0.35, summary
    assert np.mean(weight_corr_values) >= 0.95, summary
    assert np.mean(weight_spearman_values) >= 0.90, summary
    assert np.max(weight_mae_values) <= 0.10, summary
    assert np.min(weight_sign_agree_values) >= 0.95, summary
